use crate::crypto::hybrid_kem;
use ed25519_dalek::{SigningKey, VerifyingKey};
use rand_core::OsRng;
use serde::{Deserialize, Serialize};
use x25519_dalek::{PublicKey as X25519PublicKey, StaticSecret};
use zeroize::{Zeroize, ZeroizeOnDrop};

#[derive(Zeroize, ZeroizeOnDrop)]
pub struct DeviceSecrets {
    signing_key: [u8; 32],
    encryption_secret: [u8; 32],
    /// ML-KEM-768 seed (compact decapsulation-key serialization).
    pq_encryption_secret: Vec<u8>,
}

#[derive(Clone, Serialize, Deserialize, Zeroize, ZeroizeOnDrop)]
pub struct DeviceKeyMaterial {
    pub signing_key: [u8; 32],
    pub encryption_secret: [u8; 32],
    pub pq_encryption_secret: Vec<u8>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DevicePublicIdentity {
    pub signing_public_key: [u8; 32],
    pub encryption_public_key: [u8; 32],
    /// ML-KEM-768 encapsulation (public) key.
    pub pq_encryption_public_key: Vec<u8>,
}

impl DeviceSecrets {
    pub fn generate() -> Self {
        let signing = SigningKey::generate(&mut OsRng);
        let encryption = StaticSecret::random_from_rng(OsRng);
        let (_pq_public, pq_secret) = hybrid_kem::generate_keypair();
        Self {
            signing_key: signing.to_bytes(),
            encryption_secret: encryption.to_bytes(),
            pq_encryption_secret: pq_secret.pq.clone(),
        }
    }

    pub fn from_key_material(material: DeviceKeyMaterial) -> crate::Result<Self> {
        hybrid_kem::pq_public_key_from_seed(&material.pq_encryption_secret)
            .map_err(|_| crate::LinqaError::ValidationFailed("invalid PQ key material"))?;
        Ok(Self {
            signing_key: material.signing_key,
            encryption_secret: material.encryption_secret,
            pq_encryption_secret: material.pq_encryption_secret.clone(),
        })
    }

    pub fn export_key_material(&self) -> DeviceKeyMaterial {
        DeviceKeyMaterial {
            signing_key: self.signing_key,
            encryption_secret: self.encryption_secret,
            pq_encryption_secret: self.pq_encryption_secret.clone(),
        }
    }

    pub fn signing_key(&self) -> SigningKey {
        SigningKey::from_bytes(&self.signing_key)
    }

    pub fn encryption_secret(&self) -> StaticSecret {
        StaticSecret::from(self.encryption_secret)
    }

    pub fn pq_encryption_secret(&self) -> &[u8] {
        &self.pq_encryption_secret
    }

    pub fn public_identity(&self) -> DevicePublicIdentity {
        let signing = self.signing_key();
        let encryption = self.encryption_secret();
        let pq_public_key = hybrid_kem::pq_public_key_from_seed(&self.pq_encryption_secret)
            .expect("device PQ secret was generated by this module and is always valid");
        DevicePublicIdentity {
            signing_public_key: VerifyingKey::from(&signing).to_bytes(),
            encryption_public_key: X25519PublicKey::from(&encryption).to_bytes(),
            pq_encryption_public_key: pq_public_key,
        }
    }
}
