export const ALLOWED_TRANSITIONS: Record<string, string[]> = {
  CREATED: ["QUOTE_CREATED", "CANCELED"],
  QUOTE_CREATED: ["AWAITING_CONFIRMATION", "EXPIRED", "CANCELED"],
  AWAITING_CONFIRMATION: ["AUTHENTICATING", "EXPIRED", "CANCELED"],
  AUTHENTICATING: ["COMPLIANCE_SCREENING", "REQUIRES_ACTION", "DECLINED", "CANCELED"],
  COMPLIANCE_SCREENING: ["RISK_REVIEW", "MANUAL_REVIEW", "ON_HOLD", "DECLINED"],
  RISK_REVIEW: ["FUNDING_AUTHORIZATION", "MANUAL_REVIEW", "ON_HOLD", "DECLINED"],
  FUNDING_AUTHORIZATION: ["FUNDS_AUTHORIZED", "REQUIRES_ACTION", "DECLINED", "FAILED"],
  FUNDS_AUTHORIZED: ["TRANSFER_SUBMITTED", "REVERSED", "FAILED"],
  TRANSFER_SUBMITTED: ["PROCESSING", "FAILED"],
  PROCESSING: ["PAYOUT_SUBMITTED", "FAILED", "ON_HOLD"],
  PAYOUT_SUBMITTED: ["PAYOUT_PROCESSING", "COMPLETED", "FAILED"],
  PAYOUT_PROCESSING: ["COMPLETED", "FAILED", "ON_HOLD"],
  COMPLETED: ["REFUNDED", "PARTIALLY_REFUNDED", "DISPUTED", "CHARGEBACK"],
  REQUIRES_ACTION: ["AUTHENTICATING", "FUNDING_AUTHORIZATION", "EXPIRED", "CANCELED"],
  MANUAL_REVIEW: ["FUNDING_AUTHORIZATION", "DECLINED", "ON_HOLD", "CANCELED"],
  ON_HOLD: ["MANUAL_REVIEW", "PROCESSING", "DECLINED", "CANCELED"]
};

export function assertTransition(from: string, to: string) {
  if (!(ALLOWED_TRANSITIONS[from] ?? []).includes(to)) {
    throw new Error(`INVALID_TRANSFER_TRANSITION:${from}->${to}`);
  }
}
