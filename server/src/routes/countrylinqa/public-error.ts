export function publicCountryError(error: unknown): { status: number; code: string } {
  const e = error as { status?: unknown; code?: unknown } | null;
  if (typeof e?.code === "string" && publicCodes.has(e.code) && typeof e.status === "number" && Number.isInteger(e.status) && e.status >= 400 && e.status < 500) return { status: e.status, code: e.code };
  return { status: 500, code: "internal_error" };
}
