package com.linqa.app.crypto

import android.content.Context
import android.content.SharedPreferences
import android.util.Base64
import androidx.security.crypto.EncryptedSharedPreferences
import androidx.security.crypto.MasterKey
import java.nio.charset.StandardCharsets
import java.security.SecureRandom
import org.bouncycastle.crypto.agreement.X25519Agreement
import org.bouncycastle.crypto.generators.Ed25519KeyPairGenerator
import org.bouncycastle.crypto.generators.X25519KeyPairGenerator
import org.bouncycastle.crypto.params.Ed25519KeyGenerationParameters
import org.bouncycastle.crypto.params.Ed25519PrivateKeyParameters
import org.bouncycastle.crypto.params.Ed25519PublicKeyParameters
import org.bouncycastle.crypto.params.X25519KeyGenerationParameters
import org.bouncycastle.crypto.params.X25519PrivateKeyParameters
import org.bouncycastle.crypto.params.X25519PublicKeyParameters
import org.bouncycastle.crypto.signers.Ed25519Signer
import org.json.JSONArray
import org.json.JSONObject

data class DeviceKeys(
    val signingPublicKey: ByteArray,
    val encryptionPublicKey: ByteArray,
)

/**
 * This device's long-lived Ed25519 identity (signing) key and X25519
 * encryption key — generated once and persisted in Keystore-wrapped
 * EncryptedSharedPreferences. Used for the device-enrollment proof
 * signature (`network/EnrollmentApi.kt`) and E2E signaling-payload
 * encryption (`crypto/SignalingCrypto.kt`). Uses BouncyCastle rather than
 * platform `java.security` because this app's minSdk (26) predates native
 * Android X25519/Ed25519 support (API 31+/30+).
 */
class DeviceIdentity(context: Context) {
    private val prefs: SharedPreferences by lazy {
        val masterKey = MasterKey.Builder(context)
            .setKeyScheme(MasterKey.KeyScheme.AES256_GCM)
            .build()
        EncryptedSharedPreferences.create(
            context,
            "linqa-device-identity",
            masterKey,
            EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
            EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM,
        )
    }

    /** Generates and persists a keypair on first call; returns the existing
     * one on every subsequent call. */
    fun ensureKeys(): DeviceKeys {
        loadPublicKeys()?.let { return it }

        val edGenerator = Ed25519KeyPairGenerator()
        edGenerator.init(Ed25519KeyGenerationParameters(SecureRandom()))
        val edKeyPair = edGenerator.generateKeyPair()
        val edPrivate = edKeyPair.private as Ed25519PrivateKeyParameters
        val edPublic = edKeyPair.public as Ed25519PublicKeyParameters

        val xGenerator = X25519KeyPairGenerator()
        xGenerator.init(X25519KeyGenerationParameters(SecureRandom()))
        val xKeyPair = xGenerator.generateKeyPair()
        val xPrivate = xKeyPair.private as X25519PrivateKeyParameters
        val xPublic = xKeyPair.public as X25519PublicKeyParameters

        prefs.edit()
            .putString(KEY_ED_PRIVATE, encode(edPrivate.encoded))
            .putString(KEY_ED_PUBLIC, encode(edPublic.encoded))
            .putString(KEY_X_PRIVATE, encode(xPrivate.encoded))
            .putString(KEY_X_PUBLIC, encode(xPublic.encoded))
            .apply()

        return DeviceKeys(edPublic.encoded, xPublic.encoded)
    }

    fun sign(message: ByteArray): ByteArray {
        val privateKey = Ed25519PrivateKeyParameters(requireStored(KEY_ED_PRIVATE), 0)
        val signer = Ed25519Signer()
        signer.init(true, privateKey)
        signer.update(message, 0, message.size)
        return signer.generateSignature()
    }

    /** X25519 ECDH shared secret with [theirPublicKey]. */
    fun agree(theirPublicKey: ByteArray): ByteArray {
        val privateKey = X25519PrivateKeyParameters(requireStored(KEY_X_PRIVATE), 0)
        val agreement = X25519Agreement()
        agreement.init(privateKey)
        val shared = ByteArray(agreement.agreementSize)
        agreement.calculateAgreement(X25519PublicKeyParameters(theirPublicKey, 0), shared, 0)
        return shared
    }

    /**
     * The single, narrow boundary through which this device's long-term
     * private keys ever leave [DeviceIdentity] — and only as a [SecretBytes]-
     * wrapped, immediately-zeroizable blob meant for exactly one purpose:
     * binding `NativeCore`'s identity to this already-enrolled device key
     * (see `NativeCore.bindToDeviceIdentity`). No general-purpose accessor
     * for either private key exists anywhere in this class — nothing else in
     * the app can casually read these bytes.
     *
     * [pqEncryptionSecret] is generated by the caller (only the Rust core can
     * produce a valid ML-KEM-768 secret) and is consumed, not retained, here;
     * it's folded into the same sealed blob as the Ed25519/X25519 keys purely
     * so the whole `core::identity::DeviceKeyMaterial` JSON is assembled in
     * one place instead of being reconstructed field-by-field at each call
     * site.
     */
    fun sealNativeKeyMaterial(pqEncryptionSecret: ByteArray): SecretBytes {
        val signingPrivate = requireStored(KEY_ED_PRIVATE)
        val encryptionPrivate = requireStored(KEY_X_PRIVATE)
        try {
            val material = JSONObject()
                .put("signing_key", signingPrivate.toJsonArray())
                .put("encryption_secret", encryptionPrivate.toJsonArray())
                .put("pq_encryption_secret", pqEncryptionSecret.toJsonArray())
            val materialBytes = material.toString().toByteArray(StandardCharsets.UTF_8)
            return SecretBytes.takeOwnership(materialBytes)
        } finally {
            signingPrivate.fill(0)
            encryptionPrivate.fill(0)
        }
    }

    private fun ByteArray.toJsonArray(): JSONArray {
        val array = JSONArray()
        for (b in this) array.put(b.toInt() and 0xFF)
        return array
    }

    private fun loadPublicKeys(): DeviceKeys? {
        val signingPublic = prefs.getString(KEY_ED_PUBLIC, null) ?: return null
        val encryptionPublic = prefs.getString(KEY_X_PUBLIC, null) ?: return null
        return DeviceKeys(decode(signingPublic), decode(encryptionPublic))
    }

    private fun requireStored(key: String): ByteArray =
        decode(prefs.getString(key, null) ?: error("device identity not initialized"))

    private fun encode(bytes: ByteArray): String = Base64.encodeToString(bytes, Base64.NO_WRAP)
    private fun decode(value: String): ByteArray = Base64.decode(value, Base64.NO_WRAP)

    companion object {
        private const val KEY_ED_PRIVATE = "ed25519_private"
        private const val KEY_ED_PUBLIC = "ed25519_public"
        private const val KEY_X_PRIVATE = "x25519_private"
        private const val KEY_X_PUBLIC = "x25519_public"
    }
}
